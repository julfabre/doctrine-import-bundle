<?php

declare(strict_types=1);

namespace Juf\DoctrineImportBundle\Tests\Integration;

use Juf\DoctrineImportBundle\Tests\Integration\Schema\DatabaseTestCase;
use Juf\DoctrineImportBundle\Tests\Integration\Schema\Fixture\GeneratedColumnFixture;
use PHPUnit\Framework\Attributes\CoversNothing;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;

/**
 * Doctrine must never write a generated column, and must read back the value computed by the database.
 */
#[CoversNothing]
final class GeneratedColumnPersistenceTest extends DatabaseTestCase
{
    use GeneratesEntities;

    /**
     * SQLite is left out: Doctrine DBAL does not read its generated columns.
     *
     * @return iterable<string, array{string}>
     */
    public static function platformsWithGeneratedColumns(): iterable
    {
        yield 'postgresql' => ['postgresql'];
        yield 'mysql' => ['mysql'];
        yield 'mariadb' => ['mariadb'];
    }

    #[Test]
    #[DataProvider('platformsWithGeneratedColumns')]
    public function it_persists_an_entity_and_reads_back_the_value_computed_by_the_database(string $platform): void
    {
        $connection = $this->connect($platform);
        $connection->executeStatement('postgresql' === $platform
            ? 'CREATE TABLE product (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, price INT NOT NULL)'
            : 'CREATE TABLE product (id INT AUTO_INCREMENT PRIMARY KEY, price INT NOT NULL)');
        GeneratedColumnFixture::add($connection, $platform, 'product', 'price_doubled', 'price * 2');
        [$namespace, $directory] = $this->generateEntities($connection, $platform);
        $entityManager = DoctrineTestConfiguration::entityManager($connection, $directory);
        $class = $namespace.'\Product';
        if (!class_exists($class)) {
            self::fail(\sprintf('Class "%s" was not generated.', $class));
        }

        $metadata = $entityManager->getClassMetadata($class);
        $product = $metadata->newInstance();
        $metadata->setFieldValue($product, 'price', 21);
        $entityManager->persist($product);
        $entityManager->flush();

        $afterInsert = $metadata->getFieldValue($product, 'priceDoubled');
        $metadata->setFieldValue($product, 'price', 5);
        $entityManager->flush();

        self::assertSame(42, $afterInsert);
        self::assertSame(10, $metadata->getFieldValue($product, 'priceDoubled'));
    }
}

<?php

declare(strict_types=1);

namespace Juf\DoctrineImportBundle\Schema\Dbal;

use Doctrine\DBAL\Exception as DbalException;
use Doctrine\DBAL\Exception\InvalidArgumentException;
use Juf\DoctrineImportBundle\Diagnostic\Diagnostic;
use Juf\DoctrineImportBundle\Diagnostic\Severity;

/**
 * Diagnostics of the tables and columns the schema reader cannot read.
 */
final class SchemaReadingDiagnostics
{
    /**
     * DBAL reads a table as a whole: a single column of unknown type makes the whole table unreadable.
     */
    public static function unreadableTable(string $table, DbalException $exception): Diagnostic
    {
        // DBAL reports an unknown database type ("Unknown database type …") with this exception only.
        $advice = $exception instanceof InvalidArgumentException
            ? ' Map the type with the "doctrine.dbal.mapping_types" configuration, or exclude the table.'
            : '';

        return new Diagnostic(
            Severity::Error,
            'table.unreadable',
            \sprintf('Table "%s" cannot be read: %s.%s The table is skipped.', $table, rtrim($exception->getMessage(), '.'), $advice),
            $table,
        );
    }

    public static function outsideSearchPath(string $qualifiedName): Diagnostic
    {
        return new Diagnostic(
            Severity::Warning,
            'table.outside_search_path',
            \sprintf('Table "%s" is outside the default schema and was not read.', $qualifiedName),
            $qualifiedName,
        );
    }

    public static function partition(string $table): Diagnostic
    {
        return new Diagnostic(
            Severity::Info,
            'table.partition',
            \sprintf('Table "%s" is a partition: its rows are mapped through the partitioned table.', $table),
            $table,
        );
    }

    /**
     * SQLite hides generated columns from the table description that DBAL reads.
     */
    public static function generatedColumnNotRead(string $table, string $column): Diagnostic
    {
        return new Diagnostic(
            Severity::Warning,
            'column.generated_not_read',
            \sprintf('Column "%s.%s" is generated by the database, but Doctrine DBAL does not read it: it is not mapped.', $table, $column),
            $table,
            $column,
        );
    }
}
